    private var keyMessage: Data?

    /// fp-setup 第一阶段：16 字节请求，回 142 字节。
    func setup(_ request: Data) -> Data? {
        guard request.count == 16 else {
            Log.shared.warn("[AirPlay] fp-setup 长度不对：\(request.count)")
            return nil
        }
        let mode = Int(request[request.startIndex + 14])
        guard request[request.startIndex + 4] == 0x03, mode < Self.replies.count else {
            Log.shared.warn("[AirPlay] fp-setup 版本/模式不支持：版本 \(request[request.startIndex + 4])，模式 \(mode)")
            return nil
        }
        Log.shared.info("[AirPlay] fp-setup 1/2，模式 \(mode)")
        return Data(Self.replies[mode])
    }

    /// fp-setup 第二阶段：164 字节请求，回 32 字节（12 字节头 + 请求尾部 20 字节）。
    func handshake(_ request: Data) -> Data? {
        guard request.count == 164 else {
            Log.shared.warn("[AirPlay] fp-setup 2 长度不对：\(request.count)")
            return nil
        }
        keyMessage = request
        var reply = Data(Self.header)
        let start = request.startIndex
        reply.append(request.subdata(in: (start + 144)..<(start + 164)))
        Log.shared.info("[AirPlay] fp-setup 2/2 完成，已保存密钥材料")
        return reply
    }

    /// 用 SETUP 里的 ekey 推导 16 字节 AES 密钥。
    func decryptKey(_ ekey: Data) -> Data? {
        guard let keyMessage else {
            Log.shared.error("[AirPlay] 没有 fp-setup 密钥材料，无法推导 AES 密钥")
            return nil
        }
        guard ekey.count >= 72 else {
            Log.shared.error("[AirPlay] ekey 长度不对：\(ekey.count)")
            return nil
        }
        var message = [UInt8](keyMessage)
        var cipher = [UInt8](ekey.prefix(72))
        var key = [UInt8](repeating: 0, count: 16)
        playfair_decrypt(&message, &cipher, &key)
        return Data(key)
    }

    func reset() {
        keyMessage = nil
    }
